import { forwardRef } from 'react';
import './Report.css';

const AssessmentReport = forwardRef(({ predictionResult, requestData }, ref) => {
    if (!predictionResult || !requestData) return null;

    const DECISION_THRESHOLD = 0.33;
    const isAdopter = predictionResult.prediction === 'Adopter';
    const percent = (predictionResult.adopterProbability * 100).toFixed(2);

    const today = new Date().toLocaleDateString('en-GB', {
        day: 'numeric', month: 'short', year: 'numeric'
    });

    return (
        <div className="report-hidden-container">
            <div className="report-page" ref={ref}>
                <header className="report-header">
                    <div className="report-brand">
                        <span className="report-brand-mark">F</span>
                        <h2>SPARK</h2>
                    </div>
                    <div className="report-meta">
                        <h1>SME Digital Adoption Assessment</h1>
                        <p>Date: {today} | Ref: {predictionResult.refId}</p>
                    </div>
                </header>

                <section className="report-section">
                    <h3>Adoption Prediction (Random Forest)</h3>
                    <div className={`report-prediction-box ${isAdopter ? 'adopter' : 'non-adopter'}`}>
                        <div className="pred-text">
                            <span className="pred-label">Predicted Class</span>
                            <strong className="pred-result">{predictionResult.prediction}</strong>
                        </div>
                        <div className="pred-score">
                            <span className="pred-label">Adoption Probability</span>
                            <strong className="pred-percent">{percent}%</strong>
                        </div>
                    </div>
                    <p className="report-note">
                        *Prediction generated via historical formal firm data. Decision threshold set at {DECISION_THRESHOLD * 100}%.
                        This is a decision-support indicator, not a financial guarantee.
                    </p>
                </section>

                <section className="report-section">
                    <h3>SME Profile Inputs</h3>
                    <div className="profile-grid">
                        <div className="profile-item"><span>Employees:</span> <strong>{requestData.employees}</strong></div>
                        <div className="profile-item"><span>Year Started:</span> <strong>{requestData.year_started}</strong></div>
                        <div className="profile-item"><span>Sector:</span> <strong>{requestData.sector}</strong></div>
                        <div className="profile-item"><span>Financing Needed:</span> <strong>{requestData.loan_needed_not_received_count}</strong></div>
                        <div className="profile-item"><span>Has Website:</span> <strong>{requestData.has_website}</strong></div>
                        <div className="profile-item"><span>Uses Social Media:</span> <strong>{requestData.uses_social_media}</strong></div>
                        <div className="profile-item"><span>Financed Equipment:</span> <strong>{requestData.financed_equipment}</strong></div>
                        <div className="profile-item"><span>Aware of Gov Support:</span> <strong>{requestData.aware_gov_support}</strong></div>
                        <div className="profile-item"><span>Benefited from Gov Support:</span> <strong>{requestData.benefited_gov_support}</strong></div>
                        <div className="profile-item"><span>Sells via Own Website:</span> <strong>{requestData.sells_via_own_website}</strong></div>
                    </div>
                </section>

                <section className="report-section">
                    <h3>Rule-Based Policy Guidance</h3>
                    <div className="rec-box">
                        <div className="rec-row">
                            <span className="rec-label">Selected Barrier:</span>
                            <strong className="rec-barrier">{predictionResult.mainBarrier}</strong>
                        </div>
                        <div className="rec-row action-row">
                            <span className="rec-label">Recommended Action:</span>
                            <p className="rec-action">{predictionResult.recommendation}</p>
                        </div>
                    </div>
                    <p className="report-note">
                        *This recommendation is mapped via a predefined rule-based module based on your selected barrier. It is NOT generated by the AI model.
                    </p>
                </section>

                <footer className="report-footer">
                    <span>SPARK FinTech Platform</span>
                    <span>Page 1 of 1</span>
                </footer>
            </div>
        </div>
    );
});

export default AssessmentReport;